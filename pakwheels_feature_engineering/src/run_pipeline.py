# ---------------------------------------------------------------- report helpers
def fmt(value) -> str:
    if isinstance(value, str):
        return value
    if isinstance(value, (bool, np.bool_)):
        return str(value)
    if isinstance(value, (int, np.integer)):
        return f"{value:,}"
    if isinstance(value, (float, np.floating)):
        if np.isnan(value):
            return "-"
        return f"{value:,.0f}" if abs(value) >= 1000 else f"{value:,.2f}"
    return str(value)


def md_table(table: pd.DataFrame) -> str:
    header = "| " + " | ".join(map(str, table.columns)) + " |"
    divider = "|" + "|".join(["---"] * len(table.columns)) + "|"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in table.itertuples(index=False)]
    return "\n".join([header, divider, *body])


def build_report(f: dict) -> str:
    lines: list[str] = []
    add = lines.append

    add("# PakWheels data-quality and feature report")
    add("")
    add("Generated by `src/run_pipeline.py`. Re-run the pipeline to refresh every number below.")
    add("")
    add("## Summary")
    add("")
    add(f"- Raw rows: {f['raw_rows']:,}")
    add(f"- Rows used: {f['unique_ads']:,} (repeat scrapes removed: {f['repeats_removed']:,})")
    add(f"- Final model table: {f['final_rows']:,} rows x {f['final_cols']} columns")
    add(f"- Missing values left after imputation: {f['missing_after']}")
    add("")
    add("## Key findings")
    add("")
    for item in f["findings"]:
        add(f"- {item}")
    add("")
    add("## 1. Parsing and recovery rules")
    add("")
    add("Facts that the data already states, so no statistics are needed.")
    add("")
    add(md_table(f["recovery_table"]))
    add("")
    add("## 2. Missing values before imputation")
    add("")
    add(md_table(f["missing_before"]) if len(f["missing_before"]) else "No missing values.")
    add("")
    add("## 3. Statistical imputation")
    add("")
    add(md_table(f["impute_table"]))
    add("")
    k = f["knn"]
    if k:
        add(
            f"**KNN check.** On each of {k['splits']} random splits, {k['hidden']} known engine sizes were hidden "
            f"and predicted again (averaged). KNN landed within 100 cc for {k['knn_within_100']:.0%} of them "
            f"(mean error {k['knn_mae']:,.0f} cc). A single median value landed within 100 cc for "
            f"{k['median_within_100']:.0%} (mean error {k['median_mae']:,.0f} cc). "
            f"KNN is therefore used for engine size."
        )
        add("")
    add(f"## 4. Outliers (IQR rule, k = {cfg.IQR_MULTIPLIER})")
    add("")
    add("Values beyond the fences are capped to the fence. Fences for `log` columns are computed on a log1p scale. "
        "Columns with IQR = 0 are skipped, because the rule would wrongly flag every value that is not exactly that number.")
    add("")
    add(md_table(f["outlier_table"]))
    add("")
    add("## 5. Engineered features")
    add("")
    feature_table = pd.DataFrame({
        "Feature": list(ENGINEERED_FEATURES),
        "Definition": list(ENGINEERED_FEATURES.values()),
        "Spearman with price (all ads)": [f["spearman_all"][name] for name in ENGINEERED_FEATURES],
        "Spearman with price (petrol, diesel, hybrid)": [f["spearman_combustion"][name] for name in ENGINEERED_FEATURES],
    })
    add(md_table(feature_table))
    add("")
    add(
        "Spearman correlation is a rank-based measure of how closely a feature moves with price. "
        "It is shown only to check that each feature carries signal. Values are measured after imputation and capping. "
        "Other model inputs are one-hot columns for `fuel_type`, `brand` (rare brands grouped as Other) and "
        "`city` (taken from the listing URL). The most common category in each group is the reference and has no column."
    )
    add("")
    add("## 6. Before and after outlier capping")
    add("")
    add(md_table(f["before_after"]))
    add("")
    add("## Method notes")
    add("")
    add("- Order: parse, remove repeat scrapes, recover facts from text, impute, engineer features, then cap outliers. "
        "Features come before capping so that derived columns such as `km_per_year` get the same outlier check as raw columns.")
    add("- KNN for engine size uses the model family (first three words of the car name), model year, log mileage "
        "and fuel type. Price is never used to fill a feature.")
    add("- Price (the target) is capped only when `TREAT_TARGET_OUTLIERS` is True in `src/config.py`.")
    add("- Lower-tail flags for mileage and km per year are lightly used or near-new cars. They are capped like every "
        "other flag, so their mileage moves up to the lower fence.")
    add("- Scaling is left to the model step, because the right choice depends on the algorithm.")
    add("")
    return "\n".join(lines)


# ---------------------------------------------------------------- main
def _show(path: Path) -> str:
    """Show a path relative to the project when possible."""
    try:
        return str(path.relative_to(PROJECT_ROOT))
    except ValueError:
        return str(path)


def missing_summary(df: pd.DataFrame) -> pd.DataFrame:
    counts = df.isna().sum()
    counts = counts[counts > 0]
    return pd.DataFrame({
        "Column": counts.index,
        "Missing": counts.values,
        "Share of ads": [f"{count / len(df):.1%}" for count in counts.values],
    })


def main() -> None:
    if not cfg.RAW_DATA_PATH.exists():
        raise SystemExit(f"Dataset not found. Copy pakwheeldataset.csv into: {cfg.RAW_DATA_PATH.parent}")

    print("Step 1/4  Parsing text columns, removing repeat scrapes, recovering facts from text")
    raw = load_raw(cfg.RAW_DATA_PATH)
    parsed = parse_raw(raw)
    if cfg.REMOVE_REPEAT_SCRAPES:
        parsed, repeats_removed = drop_repeated_listings(parsed)
    else:
        repeats_removed = 0
    df, recovery = recover_from_text(parsed)
    print(f"          {len(raw):,} raw rows -> {len(df):,} rows used (repeat copies removed: {repeats_removed:,})")

    missing_before = missing_summary(df)
    engine_known_share = float(df.loc[df["fuel_type"].ne("Electric"), "engine_cc"].notna().mean())

    print("Step 2/4  Statistical imputation (mode / median / KNN)")
    df, impute_table, knn_check = impute_missing(df, cfg.MISSING_VALUE_METHODS, cfg.KNN_NEIGHBORS)
    if df[list(cfg.MISSING_VALUE_METHODS)].isna().any().any():
        raise RuntimeError("Imputation left missing values behind.")
    if knn_check:
        print(
            f"          engine_cc KNN check: within 100 cc = {knn_check['knn_within_100']:.0%}, "
            f"median guess = {knn_check['median_within_100']:.0%}"
        )

    print("Step 3/4  Feature engineering, then IQR outlier capping")
    df = add_engineered_features(df)
    before_outliers = df.copy()
    df, outlier_table = treat_outliers(
        df,
        cfg.OUTLIER_COLUMNS,
        cfg.OUTLIER_EXCLUDED,
        cfg.IQR_MULTIPLIER,
        cfg.TREAT_TARGET_OUTLIERS,
        cfg.TARGET,
    )
    capped = outlier_table.loc[outlier_table["Action"].eq("capped to fences"), "Column"].tolist()
    print(f"          capped columns: {', '.join(capped)}")

    print("Step 4/4  Encoding categories and saving outputs")
    model = build_model_table(df)
    if model.isna().any().any():
        raise RuntimeError("The final model table contains missing values.")
    cfg.CLEAN_DATA_PATH.parent.mkdir(parents=True, exist_ok=True)
    model.to_csv(cfg.CLEAN_DATA_PATH, index=False)

    # ---- facts for the report
    combustion_mask = df["fuel_type"].ne("Electric")
    spearman_all = spearman_with_target(df, list(ENGINEERED_FEATURES))
    spearman_combustion = spearman_with_target(df, list(ENGINEERED_FEATURES), mask=combustion_mask)
    raw_price_skew = float(before_outliers[cfg.TARGET].skew())
    ev_median = float(df.loc[~combustion_mask, cfg.TARGET].median())
    ice_median = float(df.loc[combustion_mask, cfg.TARGET].median())
    gearbox_fuel = recovery["gearbox_blank_fuel"]
    hybrid_or_electric = sum(v for key, v in gearbox_fuel.items() if key in ("Hybrid", "Electric"))
    petrol_or_diesel = sum(v for key, v in gearbox_fuel.items() if key in ("Petrol", "Diesel"))

    findings = [
        f"The raw file has {len(raw):,} rows but only {len(df):,} distinct ads. Each ad was scraped on several "
        f"dates, and some copies carry a different price. Keeping one copy per ad stops one car from appearing "
        f"in both the training and test data.",
        f"Price is strongly right-skewed (skewness {raw_price_skew:.1f} before capping), so its outliers are capped "
        f"with fences on a log scale.",
        f"Among petrol, diesel and hybrid cars, engine size is clearly linked to price "
        f"(Spearman {spearman_combustion['engine_cc']:.2f}). Only {engine_known_share:.0%} of those cars state the "
        f"engine size in the name, so the rest are estimated with KNN.",
        f"Electric cars have no engine (0 cc) but a median price of {ev_median / 1e6:.1f} million PKR, against "
        f"{ice_median / 1e6:.1f} million for the rest. Across all ads this pulls the engine correlation down to "
        f"{spearman_all['engine_cc']:.2f}, so electric cars are kept as a separate fuel group.",
        f"{recovery['gearbox_blank']:,} ads have a blank gearbox. {petrol_or_diesel:,} are petrol or diesel, "
        f"{hybrid_or_electric:,} are hybrid or electric, {recovery['gearbox_blank_auto_hint']:,} mention an automatic "
        f"gearbox in the name, and {recovery['gearbox_blank_manual_hint']:,} say manual. They are coded as "
        f"{cfg.BLANK_TRANSMISSION_VALUE}. This coding is why `is_automatic` ranks among the most informative "
        f"features (Spearman {spearman_all['is_automatic']:.2f}).",
        f"{recovery['ev_fuel_recovered']:,} electric models have a blank fuel type. They were recovered from "
        f"their model names.",
        f"{recovery['year_recovered']:,} ads have no model year, but every car name ends with one. Where both "
        f"exist, the name year matches the Model Date column for {recovery['year_agreement']:.0%} of ads, so the "
        f"name year is used.",
    ]

    recovery_table = pd.DataFrame([
        {"Rule": "Model year copied from car name", "Ads affected": recovery["year_recovered"],
         "Evidence": f"name year matches Model Date for {recovery['year_agreement']:.0%} of ads where both exist"},
        {"Rule": "Fuel set to Electric from model name", "Ads affected": recovery["ev_fuel_recovered"],
         "Evidence": "model names such as Tesla, e-tron, Leaf, EQC, MG 4 EV"},
        {"Rule": "Electric cars given 0 cc engine", "Ads affected": recovery["ev_engine_zero"],
         "Evidence": "electric cars have no engine"},
        {"Rule": f"Blank gearbox set to {cfg.BLANK_TRANSMISSION_VALUE}", "Ads affected": recovery["gearbox_blank"],
         "Evidence": "the source only records 'Automatic'; no blank ad is hybrid or electric; "
                     f"{recovery['gearbox_blank_auto_hint']} mention an automatic gearbox"},
    ])

    # Outlier counts as text so that skipped columns show "-" and counts show without decimals.
    for count_column in ["Flagged low", "Flagged high"]:
        outlier_table[count_column] = outlier_table[count_column].map(
            lambda v: "-" if pd.isna(v) else f"{int(v):,}"
        )

    before_after_cols = list(cfg.OUTLIER_COLUMNS)
    before_after = pd.DataFrame({
        "Column": before_after_cols,
        "Min before": [before_outliers[c].min() for c in before_after_cols],
        "Min after": [df[c].min() for c in before_after_cols],
        "Max before": [before_outliers[c].max() for c in before_after_cols],
        "Max after": [df[c].max() for c in before_after_cols],
        "Std before": [before_outliers[c].std() for c in before_after_cols],
        "Std after": [df[c].std() for c in before_after_cols],
    })

    facts = {
        "raw_rows": len(raw),
        "unique_ads": len(df),
        "repeats_removed": repeats_removed,
        "final_rows": len(model),
        "final_cols": model.shape[1],
        "missing_after": int(model.isna().sum().sum()),
        "findings": findings,
        "recovery_table": recovery_table,
        "missing_before": missing_before,
        "impute_table": impute_table,
        "knn": knn_check,
        "outlier_table": outlier_table,
        "spearman_all": spearman_all,
        "spearman_combustion": spearman_combustion,
        "before_after": before_after,
    }
    cfg.REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    cfg.REPORT_PATH.write_text(build_report(facts), encoding="utf-8")

    print("")
    print(f"Saved cleaned data : {_show(cfg.CLEAN_DATA_PATH)}  "
          f"({len(model):,} rows x {model.shape[1]} columns)")
    print(f"Saved report       : {_show(cfg.REPORT_PATH)}")


if __name__ == "__main__":
    main()
